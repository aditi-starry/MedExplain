def normalize_language(language: str) -> str:
    return language if language in STRINGS else "en"


def t(language: str, key: str, **kwargs) -> str:
    lang = normalize_language(language)
    template = STRINGS[lang].get(key) or STRINGS["en"].get(key, key)
    return template.format(**kwargs) if kwargs else template


def status_label(language: str, evaluation: str) -> str:
    return t(language, f"status.{evaluation or 'Not Evaluated'}")